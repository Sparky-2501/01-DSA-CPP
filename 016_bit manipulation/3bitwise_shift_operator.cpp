#include <bits/stdc++.h>
using namespace std;

int main() {
    /*
    left shift operator (<<)
    5<<1 = 10
    5<<2 = 20
    right shift operator (>>)
    5>>1 = 2
    5>>2 = 1

    */
   cout<< (5<<1) <<endl; // 10
   cout<< (5<<2) <<endl; // 20
   cout<< (10>>1) <<endl; // 5
   cout<< (5>>2) <<endl; // 1
    return 0;
}